CREATE TABLE IF NOT EXISTS `ai_rag_eval_run` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` bigint unsigned NOT NULL,
  `public_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `kb_id` bigint unsigned NOT NULL,
  `eval_name` varchar(255) NOT NULL,
  `top_k` int NOT NULL DEFAULT 5,
  `sample_count` int NOT NULL DEFAULT 0,
  `recall_at_k` decimal(8,4) NOT NULL DEFAULT 0.0000,
  `mrr` decimal(8,4) NOT NULL DEFAULT 0.0000,
  `ndcg_at_k` decimal(8,4) NOT NULL DEFAULT 0.0000,
  `hit_rate` decimal(8,4) NOT NULL DEFAULT 0.0000,
  `avg_latency_ms` bigint NOT NULL DEFAULT 0,
  `details_json` longtext DEFAULT NULL,
  `status` varchar(32) NOT NULL DEFAULT 'COMPLETED',
  `created_by` bigint unsigned NOT NULL DEFAULT 0,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_by` bigint unsigned NOT NULL DEFAULT 0,
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `deleted` tinyint(1) NOT NULL DEFAULT 0,
  `deleted_at` datetime(3) DEFAULT NULL,
  `version` int unsigned NOT NULL DEFAULT 0,
  `remark` varchar(500) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_ai_rag_eval_public_id` (`tenant_id`, `public_id`, `deleted`),
  KEY `idx_ai_rag_eval_kb` (`tenant_id`, `kb_id`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='Offline RAG retrieval evaluation runs and IR quality metrics';

